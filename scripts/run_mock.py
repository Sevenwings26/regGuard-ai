import json
import os
import sys

# Ensure repository root is on sys.path
REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from app.graph import build_investigation_graph
from app.state import verify_claims_chain

def main():
    fixture_path = os.path.join(REPO_ROOT, "app", "fixtures", "mock_case_b.json")
    with open(fixture_path, "r", encoding="utf-8") as f:
        case_data = json.load(f)
        
    initial_state = {
        "case_id": case_data["case_id"],
        "jurisdiction": case_data["jurisdiction"],
        "flagged_transaction": case_data["flagged_transaction"],
        "claims": [],
        "unresolved_questions": [],
        "retry_count": 0,
        "max_retries": 1,
        "current_node": "START",
        "event_log": [],
        "last_event_sequence": 0,
        "evidence_sufficient": False,
        "final_status": "in_progress",
        "critique_decision": None,
        "audit_memo": None,
    }
    
    print("\n=======================================================")
    print(f" RegGuard AI — Mock Run Case B: {case_data['case_id']}")
    print(f" Customer: {case_data['flagged_transaction']['customer_name']} | Flag: {case_data['flagged_transaction']['flag_reason']}")
    print("=======================================================\n")
    
    graph = build_investigation_graph()
    
    visited_nodes = []
    insufficient_events = []
    
    # Stream node execution
    for step_output in graph.stream(initial_state, stream_mode="updates"):
        for node_name, node_state in step_output.items():
            visited_nodes.append(node_name)
            print(f"[NODE ENTER] >>> {node_name.upper()}")
            
            # Inspect events generated by this node
            events = node_state.get("event_log", [])
            for event in events:
                event_type = event.get("event_type")
                seq = event.get("sequence_number")
                if event_type == "evidence_insufficient":
                    insufficient_events.append(event)
                    print(f"  [EVENT #{seq}: EVIDENCE INSUFFICIENT]")
                    print(f"    - Reason: {event['payload']['reason']}")
                    print(f"    - Missing: {event['payload']['missing']}")
                elif event_type == "claim_added":
                    print(f"  [EVENT #{seq}: CLAIM COMMITTED TO LEDGER]")
                    print(f"    - ID: {event['payload']['claim_id']}")
                    print(f"    - Hash: {event['payload']['hash'][:16]}... (prev: {event['payload']['prev_hash'][:16]}...)")
                elif event_type == "synthesis_started":
                    print(f"  [EVENT #{seq}: SYNTHESIS STARTED - PREPARING DOSSIER]")
                    print(f"    - Status: {event['payload']['status']}")
                elif event_type == "escalation":
                    print(f"  [EVENT #{seq}: HUMAN ESCALATION]")
                    print(f"    - Status: {event['payload']['status']}")
                    print(f"    - Why Unresolved: {event['payload']['why_could_not_conclude']}")

    transition_path = " -> ".join(visited_nodes)
    print("\n-------------------------------------------------------")
    print(f"Node Transition Sequence:\n  {transition_path}")
    print("-------------------------------------------------------")
    
    expected_sequence = "plan -> act -> critique -> refine -> act -> critique -> synthesize -> escalate"
    
    print(f"\n[ACCEPTANCE CHECK 1] Transition Sequence Check:")
    if transition_path == expected_sequence:
        print(f"  ✓ PASS: Exact sequence matched:\n    {transition_path}")
    else:
        print(f"  ✗ FAIL: Expected:\n    {expected_sequence}\n  Got:\n    {transition_path}")
        sys.exit(1)
        
    print(f"\n[ACCEPTANCE CHECK 2] Evidence Insufficient Events Check:")
    print(f"  Total insufficient events logged: {len(insufficient_events)}")
    if len(insufficient_events) >= 2:
        print("  ✓ PASS: Visible 'evidence insufficient' event observed between critiques and before escalation.")
        for idx, ev in enumerate(insufficient_events, 1):
            print(f"    #{idx}: {ev['payload']['reason']} | Missing: {ev['payload']['missing']}")
    else:
        print("  ✗ FAIL: Missing required evidence insufficient events.")
        sys.exit(1)

    # Full final state verification
    full_state = graph.invoke(initial_state)
    claims = full_state.get("claims", [])
    print(f"\n[ACCEPTANCE CHECK 3] Evidence Ledger & SHA-256 Hash Chain Integrity:")
    print(f"  Total claims in ledger: {len(claims)}")
    intact, broken_idx = verify_claims_chain(claims)
    if intact and len(claims) >= 2:
        print("  ✓ PASS: All claims verified. SHA-256 hash chain intact from genesis.")
        for idx, c in enumerate(claims):
            print(f"    Claim {idx+1}: [{c.claim_id}] {c.text[:65]}...")
            print(f"      Hash: {c.hash}")
            print(f"      Prev: {c.prev_hash}")
    else:
        print(f"  ✗ FAIL: Hash chain broken at index {broken_idx}")
        sys.exit(1)

    print(f"\n[ACCEPTANCE CHECK 4] Event Log Sequence Numbers (1..N no gaps):")
    event_log = full_state.get("event_log", [])
    seq_numbers = [e["sequence_number"] for e in event_log]
    expected_seq = list(range(1, len(event_log) + 1))
    if seq_numbers == expected_seq:
        print(f"  ✓ PASS: Monotonically increasing sequence numbers: 1 to {len(event_log)} (zero gaps).")
        print(f"  Events logged: {len(event_log)}")
    else:
        print(f"  ✗ FAIL: Expected sequence {expected_seq}, got {seq_numbers}")
        sys.exit(1)

    print(f"\n[ACCEPTANCE CHECK 5] Final Investigation Status & Dossier:")
    print(f"  Final Status: {full_state.get('final_status')}")
    print(f"  Retry Count:  {full_state.get('retry_count')} (Max: {full_state.get('max_retries')})")
    print(f"  Unresolved Questions Count: {len(full_state.get('unresolved_questions', []))}")
    if full_state.get("final_status") == "escalated":
        print("  ✓ PASS: Investigation successfully escalated to compliance officer (No hallucinated conclusion).")
    else:
        print(f"  ✗ FAIL: Expected final_status 'escalated', got '{full_state.get('final_status')}'")
        sys.exit(1)

    print("\n✓ ALL DAY 1 ACCEPTANCE CRITERIA SATISFIED.\n")

if __name__ == "__main__":
    main()
